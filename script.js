const sumH = (a) => +a.reduce((s, r) => s + r.h, 0).toFixed(1);
const countFin = (a, v) =>
  a.filter((r) => r.fin.toUpperCase() === v.toUpperCase()).length;

function catMap(arr) {
  const m = {};
  arr.forEach((r) => {
    const category = r.cat.trim();
    m[category] = (m[category] || 0) + 1;
  });
  return m;
}
function anaMap(arr) {
  const m = {};
  arr.forEach((r) => {
    const analysts = r.ana.split(" e ").map((name) => name.trim());
    analysts.forEach((analyst) => {
      m[analyst] = (m[analyst] || 0) + 1;
    });
  });
  return m;
}
function topN(obj, n) {
  return Object.entries(obj)
    .sort((a, b) => b[1] - a[1])
    .slice(0, n);
}
function topKey(obj) {
  const sorted = Object.entries(obj).sort((a, b) => b[1] - a[1]);
  return sorted.length > 0 ? sorted[0][0] : "N/A";
}

