(function buildTable() {
  const allCats = [
    ...new Set([
      ...Object.keys(jCM),
      ...Object.keys(fCM),
      ...Object.keys(mCM),
      ...Object.keys(aCM),
      ...Object.keys(maCM),
      ...Object.keys(junCM),
    ]),
  ];

  const rows = allCats
    .map((cat) => ({
      cat,
      jan: jCM[cat] || 0,
      feb: fCM[cat] || 0,
      mar: mCM[cat] || 0,
      abr: aCM[cat] || 0,
      mai: maCM[cat] || 0,
      jun: junCM[cat] || 0,
      tot:
        (jCM[cat] || 0) +
        (fCM[cat] || 0) +
        (mCM[cat] || 0) +
        (aCM[cat] || 0) +
        (maCM[cat] || 0) +
        (junCM[cat] || 0),
    }))
    .sort((a, b) => b.tot - a.tot)
    .slice(0, 15);

  const maxTot = rows.length > 0 ? rows[0].tot : 1;
  const tbl = document.getElementById("catTbl");

  tbl.innerHTML = `
    <thead>
      <tr>
        <th>#</th>
        <th>Categoria</th>
        <th>Jan</th><th>Fev</th><th>Mar</th><th>Abr</th><th>Mai</th><th>Jun</th>
        <th>Total</th>
        <th>Distribuição</th>
      </tr>
    </thead>
    <tbody>
      ${rows
        .map(
          (r, i) => `
        <tr>
          <td style="color:var(--muted);font-weight:800">${i + 1}</td>
          <td style="font-weight:600">${r.cat}</td>
          <td>${r.jan > 0 ? `<span class="pill jan">${r.jan}</span>` : "—"}</td>
          <td>${r.feb > 0 ? `<span class="pill feb">${r.feb}</span>` : "—"}</td>
          <td>${r.mar > 0 ? `<span class="pill mar">${r.mar}</span>` : "—"}</td>
          <td>${r.abr > 0 ? `<span class="pill abr">${r.abr}</span>` : "—"}</td>
          <td>${r.mai > 0 ? `<span class="pill mai">${r.mai}</span>` : "—"}</td>
          <td>${r.jun > 0 ? `<span class="pill jun">${r.jun}</span>` : "—"}</td>
          <td style="font-weight:800;color:var(--text)">${r.tot}</td>
          <td>
            <div style="background:var(--card2);border-radius:4px;height:6px;width:120px;overflow:hidden;display:inline-block;vertical-align:middle">
              <div style="height:100%;width:${Math.round((r.tot / maxTot) * 100)}%;background:var(--accent);border-radius:4px"></div>
            </div>
          </td>
        </tr>`,
        )
        .join("")}
    </tbody>`;
})();
